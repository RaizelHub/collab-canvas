  return new;
end;
$$;

create or replace function public.is_board_owner(
  target_board_id uuid,
  target_user_id uuid default auth.uid()
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.boards board
    where board.id = target_board_id
      and board.owner_id = target_user_id
  );
$$;

create or replace function public.board_role_for(
  target_board_id uuid,
  target_user_id uuid default auth.uid()
)
returns public.board_role
language sql
stable
security definer
set search_path = ''
as $$
  select member.role::text::public.board_role
  from public.board_members member
  where member.board_id = target_board_id
    and member.user_id = target_user_id
  limit 1;
$$;

create or replace function public.can_view_board(
  target_board_id uuid,
  target_user_id uuid default auth.uid()
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.boards board
    where board.id = target_board_id
      and (
        board.owner_id = target_user_id
        or exists (
          select 1
          from public.board_members member
          where member.board_id = board.id
            and member.user_id = target_user_id
        )
        or board.visibility::text in ('public_readonly', 'public_editable')
      )
  );
$$;

create or replace function public.shares_board_with(
  target_user_id uuid,
  requesting_user_id uuid default auth.uid()
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select target_user_id = requesting_user_id
    or exists (
      select 1
      from public.board_members mine
      join public.board_members theirs on theirs.board_id = mine.board_id
      where mine.user_id = requesting_user_id
        and theirs.user_id = target_user_id
    );
$$;

create or replace function public.accept_board_invitation(invitation_token text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  invitation public.board_invitations%rowtype;
  normalized_email text;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  normalized_email := lower(coalesce(auth.jwt() ->> 'email', ''));

  select *
  into invitation
  from public.board_invitations
  where token_hash = encode(
    extensions.digest(invitation_token, 'sha256'),
    'hex'
  )
    and accepted_at is null
    and revoked_at is null
    and expires_at > now()
  for update;

  if invitation.id is null then
    raise exception 'Invitation is invalid or expired';
  end if;

  if lower(invitation.email) <> normalized_email then
    raise exception 'Invitation email does not match the signed-in user';
  end if;

  insert into public.board_members (board_id, user_id, role, invited_by)
  values (
    invitation.board_id,
    auth.uid(),
    invitation.role,
    invitation.invited_by
  )
  on conflict (board_id, user_id) do update
  set role = case
    when public.board_members.role::text = 'owner'
      then public.board_members.role
    else excluded.role
  end;

  update public.board_invitations
  set accepted_at = now()
  where id = invitation.id;

  return invitation.board_id;
end;
$$;

