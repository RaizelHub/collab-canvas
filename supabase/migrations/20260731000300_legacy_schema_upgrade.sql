-- Remove legacy policies before installing the complete Phase 1 policy set.
do $$
declare
  policy_record record;
begin
  for policy_record in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = any (array[
        'profiles',
        'boards',
        'board_members',
        'board_invitations',
        'board_recent_access',
        'board_activity',
        'board_snapshots',
        'asset_records'
      ])
  loop
    execute format(
      'drop policy if exists %I on %I.%I',
      policy_record.policyname,
      policy_record.schemaname,
      policy_record.tablename
    );
  end loop;
end
$$;

