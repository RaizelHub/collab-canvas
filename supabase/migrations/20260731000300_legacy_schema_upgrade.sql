-- Convert legacy invitation tokens to one-way hashes before removing plaintext.
do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'board_invitations'
      and column_name = 'token'
  ) then
    execute $sql$
      update public.board_invitations
      set token_hash = encode(extensions.digest(token, 'sha256'), 'hex')
      where token_hash is null and token is not null
    $sql$;
  end if;
end
$$;

update public.board_invitations invitation
set invited_by = board.owner_id
from public.boards board
where board.id = invitation.board_id
  and invitation.invited_by is null;

do $$
begin
  if exists (
    select 1 from public.board_invitations
    where token_hash is null or invited_by is null
  ) then
    raise exception
      'Cannot upgrade invitations: an invitation is missing a token or its board owner';
  end if;
end
$$;

