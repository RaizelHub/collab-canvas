-- Upgrade an early CollabCanvas schema to the Phase 1 foundation schema.
-- This migration is intentionally data-preserving and can also run after the
-- regular foundation migrations.

create extension if not exists pgcrypto with schema extensions;

do $$
begin
  if not exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' and t.typname = 'board_visibility'
  ) then
    create type public.board_visibility as enum (
      'private',
      'organization',
      'public_readonly',
      'public_editable'
    );
  end if;

  if not exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' and t.typname = 'board_role'
  ) then
    create type public.board_role as enum ('owner', 'editor', 'viewer');
  end if;
end
$$;

do $$
begin
  if exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public'
      and t.typname = 'board_visibility'
      and t.typtype = 'e'
  ) then
    alter type public.board_visibility add value if not exists 'private';
    alter type public.board_visibility add value if not exists 'organization';
    alter type public.board_visibility add value if not exists 'public_readonly';
    alter type public.board_visibility add value if not exists 'public_editable';
  end if;

  if exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public'
      and t.typname = 'board_role'
      and t.typtype = 'e'
  ) then
    alter type public.board_role add value if not exists 'owner';
    alter type public.board_role add value if not exists 'editor';
    alter type public.board_role add value if not exists 'viewer';
  end if;
end
$$;

